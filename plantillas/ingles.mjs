// Devuelve una copia de la plantilla con todos sus textos en inglés. Avisa de los que falten.
export function traducirPlantilla(p, faltantes = new Set()) {
  const t = (s) => {
    if (!s) return s;
    if (!(s in INGLES)) { faltantes.add(s); return s; }
    return INGLES[s];
  };
  return {
    ...p, nombre: t(p.nombre), descripcion: t(p.descripcion), categoria: t(p.categoria),
    diagramas: p.diagramas.map((d) => ({
      ...d, nombre: t(d.nombre),
      pools: d.pools.map((pool) => ({ ...pool, nombre: t(pool.nombre), carriles: (pool.carriles || []).map((c) => ({ ...c, nombre: t(c.nombre) })) })),
      nodos: d.nodos.map((x) => ({ ...x, nombre: t(x.nombre), doc: t(x.doc) })),
      flujos: (d.flujos || []).map((f) => (f[2] ? [f[0], f[1], t(f[2])] : f)),
      mensajes: (d.mensajes || []).map((m) => [m[0], m[1], t(m[2])])
    }))
  };
}
